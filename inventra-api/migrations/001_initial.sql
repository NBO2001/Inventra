CREATE TABLE settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    share_mode TEXT NOT NULL DEFAULT 'ask'
        CHECK (share_mode IN ('ask', 'always', 'never'))
);

INSERT INTO settings (id, share_mode) VALUES (1, 'ask');

CREATE TABLE receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_hash TEXT NOT NULL UNIQUE,
    store TEXT NOT NULL,
    store_cnpj TEXT,
    issued_at TEXT NOT NULL,
    total TEXT NOT NULL,
    discount TEXT NOT NULL,
    approx_tax TEXT,
    shared INTEGER NOT NULL DEFAULT 0 CHECK (shared IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES receipts(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    product_key TEXT NOT NULL,
    code TEXT,
    quantity TEXT NOT NULL,
    unit TEXT NOT NULL,
    unit_price TEXT NOT NULL,
    amount TEXT NOT NULL
);

CREATE INDEX idx_items_product ON items(product_key);
CREATE INDEX idx_receipts_date ON receipts(issued_at);

CREATE TABLE dismissed_suggestions (
    product_key TEXT PRIMARY KEY,
    last_bought TEXT NOT NULL
);
